#!/usr/bin/env python3
"""Makes frontend/src/lib/thermal.js (an ES module for the website bundle) from companion/templog/thermal.js, the one
real copy of the thermal renderer. Run it after changing thermal.js:  python3 tools/sync_thermal.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'companion/templog/thermal.js').read_text()
m = re.search(r"\}\)\(typeof self !== 'undefined' \? self : this, function \(\) \{\n(.*)\n\}\);\s*$", src, re.S)
if not m:
    raise SystemExit('thermal.js is not in the expected shape')
head = src[:src.index('(function (root, factory)')]
out = ('// GENERATED by tools/sync_thermal.py from companion/templog/thermal.js: edit that file, not this one.\n' + head +
       'const HcriThermal = (function () {\n' + m.group(1) + '\n})();\nexport default HcriThermal;\n')
(root / 'frontend/src/lib/thermal.js').write_text(out)
print('wrote frontend/src/lib/thermal.js')
