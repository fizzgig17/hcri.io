// Relative power of a blackbody (T<=4000K) or CIE daylight (T>4000K)
// reference illuminant at wavelength `wl` (nm), for the given CCT -- used
// to draw the dashed reference curve on the SPD chart.
export function referenceSpectrum(wl, cct) {
  const blackbody = (w) =>
    1 / ((w * 1e-9) ** 5 * (Math.exp((6.626e-34 * 3e8) / (w * 1e-9 * 1.381e-23 * cct)) - 1));
  if (cct <= 4000) return blackbody(wl);
  const Td = Math.max(4000, Math.min(25000, cct));
  const xD = Td <= 7000
    ? -4.607e9 / Td ** 3 + 2.9678e6 / Td ** 2 + 0.09911e3 / Td + 0.244063
    : -2.0064e9 / Td ** 3 + 1.9018e6 / Td ** 2 + 0.24748e3 / Td + 0.23704;
  const yD = -3 * xD * xD + 2.87 * xD - 0.275;
  const M = 0.0241 + 0.2562 * xD - 0.7341 * yD;
  const M1 = (-1.3515 - 1.7703 * xD + 5.9114 * yD) / M;
  const M2 = (0.03 - 31.4424 * xD + 30.0717 * yD) / M;
  let idx = (wl - 300) / 10;
  let i = Math.floor(idx), frac = idx - i;
  if (i < 0) { i = 0; frac = 0; }
  if (i >= DS0.length - 1) { i = DS0.length - 2; frac = 1; }
  return (
    DS0[i] + frac * (DS0[i + 1] - DS0[i]) +
    M1 * (DS1[i] + frac * (DS1[i + 1] - DS1[i])) +
    M2 * (DS2[i] + frac * (DS2[i + 1] - DS2[i]))
  );
}
