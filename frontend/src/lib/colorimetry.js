// CIE xy → sRGB (gamut-mapped, gamma-corrected) — used to paint the
// chromaticity-diagram background.
export function xyToSrgb(x, y) {
  if (y < 1e-8) return [30, 0, 50];
  let X = (x * 1) / y, Z = ((1 - x - y) * 1) / y;
  let r = 3.2404542 * X - 1.5371385 * 1 - 0.4985314 * Z;
  let g = -0.969266 * X + 1.8760108 * 1 + 0.041556 * Z;
  let b = 0.0556434 * X - 0.2040259 * 1 + 1.0572252 * Z;
  const min = Math.min(r, g, b);
  if (min < 0) { r -= min; g -= min; b -= min; }
  const max = Math.max(r, g, b, 1e-6);
  r /= max; g /= max; b /= max;
  const gamma = (v) => (v > 0.0031308 ? 1.055 * v ** (1 / 2.4) - 0.055 : 12.92 * v);
  return [
    Math.round(gamma(Math.max(0, Math.min(1, r))) * 255),
    Math.round(gamma(Math.max(0, Math.min(1, g))) * 255),
    Math.round(gamma(Math.max(0, Math.min(1, b))) * 255),
  ];
}

// CIE xy → CIE 1960 (u,v) and CIE 1976 (u',v').
export function xyToUv(x, y) {
  const d = -2 * x + 12 * y + 3;
  return { u: (4 * x) / d, v: (6 * y) / d, up: (4 * x) / d, vp: (9 * y) / d };
}

// CIE 1960 (u,v) → xy.
export function uvToXy(u, v) {
  const d = 2 * u - 8 * v + 4;
  return d < 1e-10 ? [0.33, 0.33] : [(3 * u) / d, (2 * v) / d];
}

// CIE 1976 (u',v') → xy.
export function upvpToXy(up, vp) {
  const d = 6 * up - 16 * vp + 12;
  return d < 1e-10 ? [0.33, 0.33] : [(9 * up) / d, (4 * vp) / d];
}

// Wavelength-axis gridline positions: always includes the data range's
// endpoints, plus evenly-spaced interior ticks (step grows with the span
// so a wide range doesn't get crowded).
export function xTicks(lo, hi) {
  if (!(hi > lo)) return [lo];
  const span = hi - lo;
  const step = span <= 350 ? 50 : span <= 900 ? 100 : 200;
  const out = [];
  const start = Math.ceil(lo / step) * step;
  for (let w = start; w < hi; w += step) {
    if (w - lo > step * 0.4 && hi - w > step * 0.4) out.push(w);
  }
  out.unshift(lo);
  out.push(hi);
  return out;
}

// Normalized (unit-circle) polygon points for the Color Vector Graphic,
// from a report's real TM-30 cvgTest vectors when present, falling back to
// rcsBins/rhsBins (chroma-shift + hue-shift), and finally a flat circle.
export function cvgPolygonPoints(report) {
  const cvgTest = report && report.cvgTest;
  if (cvgTest && cvgTest.length === 16) {
    return cvgTest.map((p) => {
      const r = Math.max(0.05, Math.min(1.45, Math.hypot(p[0], p[1])));
      const a = Math.atan2(p[1], p[0]);
      return [r * Math.cos(a), r * Math.sin(a)];
    });
  }
  const rcs = report && report.rcsBins;
  const rhs = report && report.rhsBins;
  if (rcs && rcs.length === 16) {
    return rcs.map((v, i) => {
      const r = Math.max(0.05, Math.min(1.45, 1 + (+v || 0)));
      const a = ((i * 22.5 + 11.25 + (rhs && rhs.length === 16 ? +rhs[i] || 0 : 0)) * Math.PI) / 180;
      return [r * Math.cos(a), r * Math.sin(a)];
    });
  }
  return null;
}

